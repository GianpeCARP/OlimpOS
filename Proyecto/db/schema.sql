  "id_horario_actividad" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_sede" int NOT NULL,
  "id_actividad" int NOT NULL,
  -- ISO: 1 = lunes ... 7 = domingo. ISO y no el DOW nativo de Postgres
  -- (0 = domingo) porque aca la semana empieza el lunes, igual que en el
  -- calendario que ve la gente; y porque EXTRACT(ISODOW FROM fecha) devuelve
  -- exactamente esto, asi la generacion de turnos compara sin convertir nada.
  "dia_semana" int NOT NULL,
  "hora" time NOT NULL,
  "cupo" int NOT NULL,
  "id_profesor" int,
  -- Excluyente con id_profesor, igual que en Turno. Ambos NULL = sala abierta.
