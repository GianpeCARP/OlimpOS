-- ---------------------------------------------------------------------------
-- (A) EMPLEADO SIN SUBTIPO ("empleado colgado")
-- Todo Empleado debe existir en al menos uno de sus subtipos (Entrenador,
-- Nutricionista, Recepcionista, Profesor). Es una restricción de TOTALIDAD
-- de la jerarquía supertipo/subtipo, con subtipos SOLAPADOS (una persona
-- puede ser Entrenador y Profesor a la vez), así que no sirve un discriminador
-- único. Se resuelve con un CONSTRAINT TRIGGER DEFERIDO que valida al COMMIT,
-- para que el alta en dos pasos (Empleado -> subtipo) dentro de una tx pase.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION trg_empleado_debe_tener_subtipo()
RETURNS trigger AS $$
DECLARE
  v_id_empleado int;
  v_existe      boolean;
  v_tiene       boolean;
BEGIN
  -- Empleado en riesgo de quedar colgado:
  --   INSERT en Empleado          -> NEW (el recién creado)
  --   DELETE/UPDATE en un subtipo -> OLD (el que perdió el rol)
  IF TG_TABLE_NAME = 'Empleado' THEN
    v_id_empleado := NEW.id_empleado;
  ELSE
    v_id_empleado := OLD.id_empleado;
  END IF;

  -- Si el empleado ya no existe (se borró en la misma tx), no exigimos nada.
  SELECT EXISTS(SELECT 1 FROM "Empleado" WHERE id_empleado = v_id_empleado)
    INTO v_existe;
  IF NOT v_existe THEN
    RETURN NULL;
  END IF;

  SELECT
       EXISTS(SELECT 1 FROM "Entrenador"    WHERE id_empleado = v_id_empleado)
    OR EXISTS(SELECT 1 FROM "Nutricionista" WHERE id_empleado = v_id_empleado)
    OR EXISTS(SELECT 1 FROM "Recepcionista" WHERE id_empleado = v_id_empleado)
    OR EXISTS(SELECT 1 FROM "Profesor"      WHERE id_empleado = v_id_empleado)
    INTO v_tiene;

  IF NOT v_tiene THEN
    RAISE EXCEPTION
      'Empleado % no tiene subtipo. Todo empleado debe ser al menos uno de: Entrenador, Nutricionista, Recepcionista o Profesor.',
      v_id_empleado
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

